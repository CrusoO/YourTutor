import { cleanup, render, screen } from "@testing-library/react";
import { afterEach, describe, expect, it } from "vitest";
import { PitchVideoSection } from "@/components/chat/PitchVideoSection";

afterEach(cleanup);

describe("the Brownie pitch video in the video section", () => {
  it("shows the prepared pitch video with controls and its poster, and does not start by itself", () => {
    render(<PitchVideoSection />);
    const video = screen.getByTestId("pitch-video") as HTMLVideoElement;
    expect(video.getAttribute("src")).toBe("/prepared/pitch-demo.mp4");
    expect(video.getAttribute("poster")).toBe("/prepared/pitch-demo-poster.jpg");
    expect(video.controls).toBe(true);
    expect(video.autoplay).toBe(false);
  });

  it("says what it is: a Brownie-made illustration of the idea, not a recording of a result", () => {
    render(<PitchVideoSection />);
    expect(screen.getByRole("heading", { name: "Brownie in about a minute" })).toBeInTheDocument();
    const note = screen.getByTestId("pitch-note");
    expect(note).toHaveTextContent("Generated by Brownie");
    expect(note).toHaveTextContent("illustration");
    expect(note).toHaveTextContent("not a recording");
  });

  it("is a labelled region with a spoken name for the video", () => {
    render(<PitchVideoSection />);
    expect(screen.getByRole("region", { name: "Brownie in about a minute" })).toBeInTheDocument();
    expect(screen.getByTestId("pitch-video")).toHaveAttribute("aria-label", "Brownie in about a minute");
  });
});
